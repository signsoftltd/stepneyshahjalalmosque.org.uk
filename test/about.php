            <div class="ab-story ev-rich" data-ab="story_html">
              <p>The London Borough of Tower Hamlets is home to a dense Muslim population, Stepney Green. Before 1980, local Muslims did not have a Masjid where they could come together for daily prayers or to run Islamic activities. Muslim residents would move from neighbour to neighbour’s home to pray in congregation, however as the number of worshippers grew, it soon became clear the need for a Mosque.</p>
              <p>In 1985, Stepney Shahjalal Masjid was formed on the grounds of Shandy Park. It was named after Hazrat Shah Jalal Mujarrad al Yemeni (RA) who migrated to Bangladesh from the Middle East to promote Islamic education and Dawah activities within the Sylhet region of Bangladesh.</p>
              <p>The Mosque is managed by a board of trustees, who are elected every two years by members of the Mosque. The activities and financial matters are regulated by the Charity Commission and Company law in UK. To support the running of the Mosque and its activities, there is an advisory board which comprises of Imams, Islamic scholars and community leaders.</p>
