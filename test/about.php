      <ol class="ab-timeline" data-ab-list="milestones">
        <li><span class="ab-year">1980</span><div><h3>Prayers in residents’ homes</h3><p>Tarawih prayer and five daily prayer took place in various residents’ homes.</p></div></li>
        <li><span class="ab-year">1981</span><div><h3>Mosque Committee formed</h3><p>Stepney Shahjalal Mosque Committee was formed.</p></div></li>
        <li><span class="ab-year">1985</span><div><h3>A prayer hall in Shandy Park</h3><p>Prayer facilities moved into the caretaker hut on the grounds of Shandy Park, accommodating up to 50 worshippers.</p></div></li>
        <li><span class="ab-year">1990</span><div><h3>Portable cabins and Islamic classes</h3><p>Tower Hamlets Council grants permission to extend the facilities by installing portable cabins, allowing local children to attend Islamic education classes. Further extensions were built to accommodate the increasing number of worshippers.</p></div></li>
        <li><span class="ab-year">1992</span><div><h3>Registered as a Place of Worship</h3><p>The mosque was registered as a Place of Worship under Worship &amp; Registration Act 1855.</p></div></li>
        <li><span class="ab-year">1999</span><div><h3>Registered charity and company</h3><p>Registered as a Charity with Charity Commission and a Company limited by guarantee with Companies House.</p></div></li>
        <li><span class="ab-year">2002</span><div><h3>Freehold land purchased</h3><p>With the support of the local community, freehold land was purchased from Tower Hamlets Council for a purpose-built Stepney Shahjalal Mosque and Cultural Centre on the grounds of Shandy Park.</p></div></li>
        <li><span class="ab-year">2005</span><div><h3>Room for 800 worshippers</h3><p>Additional portable buildings were added to accommodate approximately 800 worshippers inside the Mosque, however, about 500-700 additional worshippers still pray outside the Mosque in Park every Jummah and Ramadan in the rain, snow and in extreme cold and hot weather.</p></div></li>
        <li><span class="ab-year">2010</span><div><h3>Planning permission granted</h3><p>Full planning permission with conditions was granted to build a new Mosque and community facilities large enough to accommodate more than 3000 men, women and children.</p></div></li>
        <li><span class="ab-year">2013</span><div><h3>Works begin towards the new Mosque</h3><p>All essential pre-conditions were approved and pre-commencement work began, however archaeological watching brief and Ministry of Justice permission were required for foundation design, due to the archaeological importance of Mosque land. The project was split into two phases; Phase one: Mosque and Phase two: Community Centre. A temporary Mosque was erected on the community centre site by installing portable building to accommodate 700-800 worshippers and to run Islamic education facilities for men, women, boys and girls.</p></div></li>
        <li><span class="ab-year">2014–2016</span><div><h3>Demolition and design approval</h3><p>Demolition of old Porta Cabin Mosque. Architect, Structural engineer, building control, Fire consultant, Health &amp; safety Officer, Archaeologist and Quantity Surveyor hired. Foundation design was approved by Ministry of Justice (MOJ).</p></div></li>
        <li><span class="ab-year">2016</span><div><h3>Contractor appointed and foundation stone laid</h3><p>Tendering and appointment of Brook William contractor to build phase one – Masjid to accommodate approximately 1500 worshippers. Fund is needed 3.5 million pounds for this phase. Foundation stone laying ceremony took place on 7 November 2016 with participations local imams, community leaders, elders and youth.</p></div></li>
        <li><span class="ab-year">2017</span><div><h3>Detailed drawings completed</h3><p>Alhamdulillah, our appointed architect, structural engineer, M&amp;E engineers, quantity surveyor and archaeology consultants have completed details drawings for tendering. The foundation design was approved by MOJ and archaeological watching briefs has now ended.</p></div></li>
